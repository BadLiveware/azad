//! Targets across packages, tags, and the filter that selects by them (decision 0023), with host tasks in a git
//! workspace.
#![allow(clippy::unwrap_used)]

use std::collections::BTreeSet;
use std::fs;
use std::path::Path;
use std::process::Command;
use std::time::Duration;

use azad::engine::{Engine, EngineConfig, EngineError, Event, Status, TagFilter, host_platform};
use azad::frontend::{Note, NoteLevel};
use azad::sandbox::Limits;
use tempfile::TempDir;

fn write(root: &Path, path: &str, content: &str) {
    let path = root.join(path);
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, content).unwrap();
}

fn fmt(tags: &[&str]) -> String {
    format!("fmt = task(name = \"fmt\", cmd = \"true\", tags = {tags:?})\n")
}

/// A repository: the apps get the tag `app` from their `config.star`; `services/orders` formats only after its code is
/// generated by a task tagged `codegen`; `docs` has no `fmt`.
fn workspace() -> TempDir {
    let dir = TempDir::new().unwrap();
    let root = dir.path();
    let git = Command::new("git").args(["init", "-q"]).current_dir(root).status().unwrap();
    assert!(git.success());
    write(root, ".gitignore", ".store/\ngenerated/\n");
    write(root, "apps/config.star", "tags = [\"app\"]\n");
    write(root, "apps/ios/config.star", "tags = [\"ios\"]\n");
    write(root, "apps/ios/tasks.star", &fmt(&["swift"]));
    write(root, "apps/android/tasks.star", &fmt(&["gradle"]));
    write(root, "services/billing/tasks.star", &fmt(&["dotnet"]));
    write(
        root,
        "services/orders/tasks.star",
        "gen = task(name = \"gen\", cmd = \"mkdir -p generated && touch generated/code\", generates = [\"generated\"], \
         tags = [\"codegen\"])\n\
         fmt = task(name = \"fmt\", cmd = \"test -e generated/code\", deps = [gen], tags = [\"dotnet\"])\n\
         goal(\"check\", require = [fmt])\n",
    );
    write(root, "docs/tasks.star", "readme = task(name = \"readme\", cmd = \"true\")\n");
    dir
}

fn engine(dir: &TempDir, filter: TagFilter) -> Engine {
    Engine::new(EngineConfig {
        store: dir.path().join(".store"),
        root: dir.path().to_path_buf(),
        platform: host_platform(),
        limits: Limits { timeout: Duration::from_secs(30), ..Limits::default() },
        tools: Default::default(),
        isolated: false,
        color: false,
        force: false,
        sandbox: azad::SandboxKind::Bubblewrap,
        executor: None,
        trust: azad::Trust::Main,
        history: None,
        withheld: Default::default(),
        filter,
        local: None,
    })
    .unwrap()
}

fn filter(include: &[&str], exclude: &[&str]) -> TagFilter {
    let set = |tags: &[&str]| tags.iter().map(|tag| (*tag).to_owned()).collect();
    TagFilter { include: set(include), exclude: set(exclude), origin: "the test".to_owned() }
}

/// The packages whose `fmt` a run of `target` needed (it ran, or its result was known), and the notes of the load.
fn formatted(dir: &TempDir, target: &str, filter: TagFilter) -> (BTreeSet<String>, Vec<Note>) {
    let engine = engine(dir, filter);
    let mut notes = Vec::new();
    let goal = engine
        .load(target, &mut |event| {
            if let Event::Note(note) = event {
                notes.push(note);
            }
        })
        .unwrap();
    let report = engine.run(&goal, 4, &mut |_| {}).unwrap();
    assert!(report.outcome.goal_holds(), "{:?}", report.outcome.statuses);
    let needed = report
        .outcome
        .statuses
        .iter()
        .filter(|(_, status)| !matches!(status, Status::NotNeeded))
        .filter_map(|(label, _)| label.strip_prefix("//")?.strip_suffix(":fmt").map(str::to_owned))
        .collect();
    (needed, notes)
}

fn set(packages: &[&str]) -> BTreeSet<String> {
    packages.iter().map(|package| (*package).to_owned()).collect()
}

#[test]
fn a_pattern_runs_the_goal_of_every_package_at_or_below_its_directory() {
    let dir = workspace();
    let all = set(&["apps/android", "apps/ios", "services/billing", "services/orders"]);
    assert_eq!(formatted(&dir, "//...:fmt", TagFilter::default()).0, all);
    assert_eq!(formatted(&dir, "//apps/...:fmt", TagFilter::default()).0, set(&["apps/android", "apps/ios"]));
    assert_eq!(formatted(&dir, "//services/orders/...:fmt", TagFilter::default()).0, set(&["services/orders"]));

    let error = engine(&dir, TagFilter::default()).load("//docs/...:fmt", &mut |_| {}).unwrap_err();
    assert!(matches!(error, EngineError::NoPackageDefines { .. }), "{error}");
}

#[test]
fn the_filter_selects_by_the_tags_of_tasks_and_of_the_config_above_them() {
    let dir = workspace();
    let (ran, notes) = formatted(&dir, "//...:fmt", filter(&[], &["app"]));
    assert_eq!(ran, set(&["services/billing", "services/orders"]));
    let normal: Vec<&str> =
        notes.iter().filter(|note| note.level == NoteLevel::Normal).map(|note| note.text.as_str()).collect();
    assert_eq!(normal, vec!["//...:fmt: skipped 2 tasks tagged app (the test)"]);
    assert!(notes.iter().any(|note| note.level == NoteLevel::Diagnostic && note.text.contains("//apps/ios:fmt")));

    assert_eq!(formatted(&dir, "//...:fmt", filter(&["ios"], &[])).0, set(&["apps/ios"]));
    assert_eq!(
        formatted(&dir, "//...:fmt", filter(&["dotnet", "app"], &["ios"])).0,
        set(&["apps/android", "services/billing", "services/orders"])
    );
}

#[test]
fn what_a_selected_task_needs_runs_whatever_its_tags() {
    let dir = workspace();
    assert_eq!(
        formatted(&dir, "//services/...:fmt", filter(&[], &["codegen"])).0,
        set(&["services/billing", "services/orders"])
    );
}

#[test]
fn a_target_whose_tasks_are_all_excluded_says_so() {
    let dir = workspace();
    for target in ["//apps/...:fmt", "//apps/ios:fmt"] {
        let error = engine(&dir, filter(&[], &["app"])).load(target, &mut |_| {}).unwrap_err();
        assert!(matches!(error, EngineError::AllExcluded { .. }), "{target}: {error}");
        assert!(error.to_string().contains("//apps/ios:fmt"), "{error}");
    }
}
